// The language is also cached in localStorage (extension pages only) so a page can be translated at once,
// without waiting for chrome.storage; the stored setting is then checked and wins if it differs.
function cachedLanguageSetting() {
  try {
    return localStorage.getItem("language");
  } catch (e) {
    return null;
  }
}

let currentLang = "en";

// The locale for dates and numbers in the current language (undefined = the browser's own).
const dateLocale = () => ({ ja: "ja-JP", zh: "zh-CN" })[currentLang];

function resolveLanguage(setting) {
  if (setting === "en" || setting === "ja" || setting === "zh") return setting;
  const browser = typeof navigator !== "undefined" ? String(navigator.language || "en").toLowerCase() : "en";
  if (browser.startsWith("ja")) return "ja";
  return browser.startsWith("zh") ? "zh" : "en";
}

// The text for a key in the current language (English if missing, the key itself as a last resort).
function tr(key, vars) {
  const table = I18N[currentLang] || I18N.en;
  let text = key in table ? table[key] : key in I18N.en ? I18N.en[key] : key;
  if (vars) text = text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? vars[name] : match));
  return text;
}

// Put the texts of the current language into everything marked with data-i18n* in the page.
function translatePage(root) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = tr(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = tr(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = tr(el.dataset.i18nPlaceholder);
}

async function setLanguageFromStorage() {
  const { language } = await chrome.storage.local.get("language");
  currentLang = resolveLanguage(language);
  try {
    localStorage.setItem("language", language || "auto");
  } catch (e) {}
}

// Pages wait for this before showing any text built by scripts: `await i18nReady`.
let i18nReady = Promise.resolve();
if (typeof document !== "undefined" && typeof chrome !== "undefined" && chrome.storage) {
  currentLang = resolveLanguage(cachedLanguageSetting());
  const translateNow = () => {
    document.documentElement.lang = currentLang;
    translatePage(document);
  };
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", translateNow);
  else translateNow();
  i18nReady = setLanguageFromStorage().then(() => {
    // Only needed when the cached language was out of date. (Texts that scripts fill in carry no data-i18n,
    // so translating again can never overwrite them.)
    if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", translateNow);
    else translateNow();
  });
}
